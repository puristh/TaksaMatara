export type TierTableLookupResult = { tier: TierKey; note?: string } | null;

/**
 * bidirectional lookup: เช็คทั้ง XY และ YX เสมอ ตามที่ brief เน้นย้ำ (ข้อ 3.2, ข้อ 4 Mode 2)
 * ลำดับการเช็ค: tier1 > tier2 > tier2_5 > tier3 > tier4 (explicit list) > tier4 (zero rule)
 */
export function lookupTier(pair: string): TierTableLookupResult {
  const n = Number(pair);
  const reversed = pair.length === 2 ? pair[1] + pair[0] : pair;
  const rn = Number(reversed);

  const inList = (list: number[]) => list.includes(n) || list.includes(rn);

  if (inList(TIER1)) return { tier: 'tier1' };
  if (inList(TIER2)) return { tier: 'tier2' };
  if (pair in TIER2_5) return { tier: 'tier2_5', note: TIER2_5[pair] };
  if (reversed in TIER2_5) return { tier: 'tier2_5', note: TIER2_5[reversed] };
  if (inList(TIER3)) return { tier: 'tier3' };
  if (inList(TIER4_EXPLICIT)) return { tier: 'tier4' };
  if (isTier4ByZeroRule(n) || isTier4ByZeroRule(rn)) return { tier: 'tier4' };

  return null;
}

